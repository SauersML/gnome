"""Writes src/server/bee-words.ts: the words the bee knows (every word seen at least 3 times in
100 MB of TinyStories, or twice in her post-training data), which the Worker uses to prefer
drafts made of words over drafts made of half-words.
Usage: python train/bee_words.py <TinyStories train .txt>
"""
import collections
import glob
import json
import re
import sys

WORD = re.compile(r"[A-Za-z]{2,}")


def main():
    stories = collections.Counter()
    with open(sys.argv[1], encoding="utf-8", errors="ignore") as f:
        for _ in range(10):
            stories.update(w.lower() for w in WORD.findall(f.read(10_000_000)))
    bee = collections.Counter()
    for path in sorted(glob.glob("train/data/*.jsonl")):
        for line in open(path):
            for turn in json.loads(line)["turns"]:
                bee.update(w.lower() for w in WORD.findall(turn["content"]))
    words = sorted({w for w, n in stories.items() if n >= 3} | {w for w, n in bee.items() if n >= 2})
    with open("src/server/bee-words.ts", "w") as out:
        out.write("// Generated by train/bee_words.py: the words the bee knows, space-separated.\n")
        out.write(f'export const BEE_WORDS = "{" ".join(words)}";\n')
    print(f"{len(words)} words")


if __name__ == "__main__":
    main()
